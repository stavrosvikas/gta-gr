# Rebuilds js/sounds_list.js from the files in assets/sounds/.
# Run it after adding or removing a sound:  python update_sounds.py
import os, json
here = os.path.dirname(os.path.abspath(__file__))
d = os.path.join(here, 'assets', 'sounds')
files = {}
for f in sorted(os.listdir(d)):
    k, ext = os.path.splitext(f)
    ext = ext[1:].lower()
    if ext in ('mp3', 'wav', 'ogg', 'm4a') and k not in files:
        files[k] = [ext, os.path.getsize(os.path.join(d, f))]
with open(os.path.join(here, 'js', 'sounds_list.js'), 'w', encoding='utf-8') as out:
    out.write('// generated by update_sounds.py: every file in assets/sounds/ as key: [ext, bytes]\n')
    out.write('window.SOUND_FILES = ' + json.dumps(files, separators=(',', ':')).replace('],', '],\n') + ';\n')
print(len(files), 'sounds')
